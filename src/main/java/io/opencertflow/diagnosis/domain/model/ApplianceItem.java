package io.opencertflow.diagnosis.domain.model;

/**
 * 「전기용품 및 생활용품 안전관리법 시행규칙」 별표의 <b>품목</b>.
 *
 * <p>인증 등급은 제품군이 아니라 <b>품목 단위</b>로 정해진다. 별표 3은 안전인증대상,
 * 별표 4는 안전확인대상, 별표 5는 공급자적합성확인대상을 각각 나열한다. 같은 '소형가전'
 * 안에도 세 등급이 모두 들어 있으므로, 제품군 하나에 등급 하나를 붙이면 반드시 누군가는
 * 틀린 안내를 받는다.
 *
 * <p><b>여기 없는 품목은 {@link #OTHER}다.</b> 목록을 늘리는 것은 별표를 확인한 만큼만 한다 —
 * 추측으로 채우면 그 추측이 사용자에게는 확정된 답으로 보인다. 확인 절차는 CONTRIBUTING의
 * '인증 등급을 확인하는 절차'에 있다.
 *
 * <p>괄호 안은 근거 조항이다. 법령이 개정되면 그 번호로 다시 찾을 수 있다.
 */
public enum ApplianceItem {

    // ── 별표 3 · 안전인증대상전기용품 (제품시험 + 공장심사) ──────────

    /** 별표 3 · 2) 전기다리미 및 전기프레스기 */
    ELECTRIC_IRON,

    /** 별표 3 · 3) 주방용전열기구 */
    KITCHEN_HEATING_APPLIANCE,

    /** 별표 3 · 5) 모발관리기 — 헤어드라이어·모발건조기가 여기 해당한다 */
    HAIR_CARE_DEVICE,

    /** 별표 3 · 8) 전기액체가열기기 */
    LIQUID_HEATING_APPLIANCE,

    /** 별표 3 · 16) 전열기구 */
    HEATING_APPLIANCE,

    /** 별표 3 · 17) 전기마사지기 */
    ELECTRIC_MASSAGER,

    /** 별표 3 · 25) 가습기 */
    HUMIDIFIER,

    // ── 별표 4 · 안전확인대상전기용품 (시험성적서 제출 후 신고) ──────

    /** 별표 4 · 3) 이·미용기기 */
    BEAUTY_DEVICE,

    /** 별표 4 · 7) 구강청결기 */
    ORAL_CLEANER,

    /** 별표 4 · 42) 전기청소기 */
    VACUUM_CLEANER,

    /** 별표 4 · 45) 전기건조기 — 손·발·의류·농산물 등을 건조하는 것. 모발은 여기가 아니다 */
    DRYING_APPLIANCE,

    // ── 그 밖 ────────────────────────────────────────────────────

    /**
     * 위 목록에 없는 품목.
     *
     * <p>별표에 없다는 뜻이 아니라 <b>이 서비스가 아직 확인하지 않았다</b>는 뜻이다.
     * 등급을 단정하지 않고 전문가 확인으로 보낸다.
     */
    OTHER,

    /** 사용자가 선택하지 않았다. 없음이 아니라 <b>모름</b>이다. */
    UNKNOWN
}
