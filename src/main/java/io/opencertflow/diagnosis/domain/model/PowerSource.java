package io.opencertflow.diagnosis.domain.model;

/**
 * 전원 방식. 교류인지 직류인지.
 *
 * <p><b>이 구분이 인증 등급을 가른다.</b> 「전기용품 및 생활용품 안전관리법 시행규칙」은 같은 품목도
 * 전원 방식에 따라 다른 별표에 넣는다. 전기찜질기(전기방석·전기요 포함)를 보면 —
 *
 * <ul>
 *   <li><b>별표 3</b> 안전인증대상전기용품 · 10) <b>교류전원</b>을 사용하는 전기찜질기, 발 보온기
 *   <li><b>별표 5</b> 공급자적합성확인대상전기용품 · 16) <b>직류전원</b>을 사용하는 전기찜질기 및 발 보온기
 * </ul>
 *
 * <p>둘의 무게가 전혀 다르다. 안전인증은 인증기관 심사와 공장심사를 거치고, 공급자적합성확인은
 * 제조·수입자가 스스로 확인해 신고한다. 직류 제품 제조자에게 안전인증을 안내하면 필요 없는 비용을
 * 물리는 것이다 — 그래서 정격전압이나 배터리 유무로 <b>추측하지 않고</b> 입력으로 받는다.
 *
 * <p>{@link #UNKNOWN}을 별도로 두는 이유도 같다. 모르는 것을 교류로 뭉개면 과잉 안내가 되고,
 * 직류로 뭉개면 과소 안내가 된다. 모르면 전문가 확인으로 보낸다.
 */
public enum PowerSource {

    /** 교류(AC). 콘센트에 직접 꽂는 220V 제품이 여기 해당한다. */
    AC,

    /** 직류(DC). 어댑터로 낮춰 쓰거나 배터리로 동작하는 제품. */
    DC,

    /** 확인되지 않음. 없음이 아니라 <b>모름</b>이다. */
    UNKNOWN
}
