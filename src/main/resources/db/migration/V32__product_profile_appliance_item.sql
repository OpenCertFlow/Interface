-- 시행규칙 별표의 품목을 제품 프로필에 추가한다.
--
-- 왜 필요한가: 인증 등급은 제품군이 아니라 <품목> 단위로 정해진다. 별표 3(안전인증)·
-- 별표 4(안전확인)·별표 5(공급자적합성확인)가 각각 품목을 나열하며, 같은 '소형가전' 안에도
-- 세 등급이 모두 들어 있다.
--
--   별표 3 ·  5) 모발관리기          → 안전인증 (헤어드라이어)
--   별표 4 ·  3) 이·미용기기         → 안전확인
--   별표 4 · 42) 전기청소기          → 안전확인
--
-- 제품군 하나에 등급 하나를 붙이면 반드시 누군가는 틀린 안내를 받는다. 실제로 기존
-- R-SA-001은 소형가전 전체에 안전확인을 붙였고, 그 결과 헤어드라이어(안전인증 대상)에
-- 받아야 할 인증을 축소해 안내하고 있었다.

ALTER TABLE product_profile
    ADD COLUMN appliance_item varchar(40) NOT NULL DEFAULT 'UNKNOWN';

COMMENT ON COLUMN product_profile.appliance_item IS
    '시행규칙 별표의 품목. 인증 등급 판정의 기준이며, UNKNOWN은 없음이 아니라 모름이다';

-- 기존 진단은 이 값을 입력받은 적이 없다. UNKNOWN으로 남겨 '모른다'를 그대로 보존한다 —
-- 제품명으로 추정해 채우면 재현했을 때 원래 진단과 다른 결과가 나온다(재현성 우선).
