-- 전원 방식(교류/직류/모름)을 제품 프로필에 추가한다.
--
-- 왜 필요한가: 「전기용품 및 생활용품 안전관리법 시행규칙」이 같은 품목도 전원 방식에 따라
-- 다른 별표에 넣기 때문이다. 전기찜질기(전기방석 포함)를 보면 —
--   별표 3 안전인증대상전기용품          10) 교류전원을 사용하는 전기찜질기, 발 보온기
--   별표 5 공급자적합성확인대상전기용품  16) 직류전원을 사용하는 전기찜질기 및 발 보온기
-- 안전인증은 인증기관 심사와 공장심사를 거치고, 공급자적합성확인은 스스로 확인해 신고한다.
-- 직류 제품에 안전인증을 안내하면 필요 없는 비용을 물리게 된다.
--
-- 정격전압이나 배터리 유무로 추론하지 않는다. 24V 교류와 24V 직류를 구별할 수 없고,
-- 추론이 틀리면 그 사실이 조용히 묻힌다.

ALTER TABLE product_profile
    ADD COLUMN power_source varchar(20) NOT NULL DEFAULT 'UNKNOWN';

COMMENT ON COLUMN product_profile.power_source IS
    '전원 방식: AC(교류) · DC(직류) · UNKNOWN(모름). 인증 등급을 가르는 값이며, 모름은 없음이 아니다';

-- 기존 진단은 이 값을 입력받은 적이 없다. UNKNOWN으로 남겨 "모른다"를 그대로 보존한다 —
-- 220V였을 것이라 추정해 AC로 채우면, 재현했을 때 원래 진단과 다른 결과가 나온다.
-- 진단은 평가 시점의 입력을 그대로 들고 있어야 한다(재현성 우선).
